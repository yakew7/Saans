import { categoryFor, CATEGORIES } from "./aqi/categories";
import { fmtNum } from "./format";
import { linearTrend, mean, trendOf, type Trend } from "./aqi/stats";
import { WHO_2021, cigaretteEquivalent } from "./aqi/who";
import { summarisePeriod, type DayValue, type DaySpike } from "./history";

/** Pure analysis for the Pollution Impact Report (shared by server route, UI text export and tests). */
export interface ReportStats {
  start: string;
  end: string;
  totalDays: number;
  validDays: number;
  meanAqi: number | null;
  meanPm25: number | null;
  meanPm10: number | null;
  best: { date: string; aqi: number } | null;
  worst: { date: string; aqi: number } | null;
  worstFive: { date: string; aqi: number }[];
  daysAboveWhoPm25: number;
  daysAboveWhoPm10: number;
  daysWithPm25: number;
  daysWithPm10: number;
  categoryDays: { id: string; label: string; color: string; days: number }[];
  trend: Trend;
  /** AQI points per day from a least-squares line */
  trendSlope: number | null;
  spikes: DaySpike[];
  /** total "cigarette equivalents" over the period: sum(daily PM2.5 / 22). A rough heuristic. */
  cigarettes: number | null;
  cigarettesPerDay: number | null;
}

export function buildReport(allDays: DayValue[], start: string, end: string): ReportStats {
  const p = summarisePeriod(allDays, start, end);
  const days = p.days;
  const aqiDays = days.filter((d): d is DayValue & { aqi: number } => d.aqi != null);
  const pm25 = days.filter((d): d is DayValue & { pm25: number } => d.pm25 != null);
  const pm10 = days.filter((d): d is DayValue & { pm10: number } => d.pm10 != null);
  const sorted = [...aqiDays].sort((a, b) => b.aqi - a.aqi);
  const aqiVals = aqiDays.map((d) => d.aqi);
  const lt = linearTrend(aqiVals);
  const cig = pm25.map((d) => cigaretteEquivalent(d.pm25)!);
  const totalDays = Math.round((Date.parse(`${end}T00:00:00Z`) - Date.parse(`${start}T00:00:00Z`)) / 86_400_000) + 1;
  return {
    start,
    end,
    totalDays,
    validDays: aqiDays.length,
    meanAqi: mean(aqiVals),
    meanPm25: mean(pm25.map((d) => d.pm25)),
    meanPm10: mean(pm10.map((d) => d.pm10)),
    best: sorted.length ? { date: sorted.at(-1)!.date, aqi: sorted.at(-1)!.aqi } : null,
    worst: sorted.length ? { date: sorted[0].date, aqi: sorted[0].aqi } : null,
    worstFive: sorted.slice(0, 5).map((d) => ({ date: d.date, aqi: d.aqi })),
    daysAboveWhoPm25: pm25.filter((d) => d.pm25 > WHO_2021.pm25.shortTerm).length,
    daysAboveWhoPm10: pm10.filter((d) => d.pm10 > WHO_2021.pm10.shortTerm).length,
    daysWithPm25: pm25.length,
    daysWithPm10: pm10.length,
    categoryDays: CATEGORIES.map((c) => ({ id: c.id, label: c.label, color: c.color, days: aqiDays.filter((d) => categoryFor(d.aqi).id === c.id).length })),
    trend: trendOf(aqiVals, 0.1),
    trendSlope: lt?.slope ?? null,
    spikes: p.spikes,
    cigarettes: cig.length ? cig.reduce((a, b) => a + b, 0) : null,
    cigarettesPerDay: cig.length ? mean(cig) : null,
  };
}

/** Plain-text version for "Copy as text". */
export function reportToText(place: string, r: ReportStats, source: string): string {
  const L: string[] = [
    `POLLUTION IMPACT REPORT: ${place}`,
    `Period: ${r.start} to ${r.end} (${r.validDays} of ${r.totalDays} days with data)`,
    `Data: ${source}`,
    "",
  ];
  if (!r.validDays) return [...L, "No data available for this period."].join("\n");
  L.push(
    `Average daily AQI (US EPA): ${fmtNum(r.meanAqi)}${r.meanAqi != null ? ` (${categoryFor(r.meanAqi).label})` : ""}`,
    `Average PM2.5: ${fmtNum(r.meanPm25, 1)} µg/m³ | Average PM10: ${fmtNum(r.meanPm10, 1)} µg/m³`,
    `Best day: ${r.best ? `${r.best.date} (AQI ${r.best.aqi})` : "n/a"}`,
    `Worst day: ${r.worst ? `${r.worst.date} (AQI ${r.worst.aqi})` : "n/a"}`,
    `Days above the WHO 24 h guideline: PM2.5 ${r.daysAboveWhoPm25} of ${r.daysWithPm25} days (guideline ${WHO_2021.pm25.shortTerm} µg/m³); PM10 ${r.daysAboveWhoPm10} of ${r.daysWithPm10} days (guideline ${WHO_2021.pm10.shortTerm} µg/m³)`,
    `Trend: ${r.trend}${r.trendSlope != null ? ` (${r.trendSlope > 0 ? "+" : ""}${r.trendSlope.toFixed(1)} AQI points per day)` : ""}`,
    `Days by category: ${r.categoryDays.filter((c) => c.days).map((c) => `${c.label} ${c.days}`).join(", ")}`,
    r.spikes.length ? `Spikes: ${r.spikes.map((s) => `${s.date} (AQI ${s.aqi}, typical ${Math.round(s.baseline)})`).join("; ")}` : "Spikes: none detected",
    r.cigarettes != null ? `Cigarette-equivalent (rough heuristic, Berkeley Earth: ~22 µg/m³ PM2.5 over 24 h ≈ 1 cigarette/day): about ${r.cigarettes.toFixed(0)} cigarettes over the period, ${r.cigarettesPerDay!.toFixed(1)} per day on average` : "",
    "",
    "Generated by Saans. Not medical advice.",
  );
  return L.filter((x) => x !== "").join("\n");
}
